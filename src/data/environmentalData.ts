// Generates authentic time-series for 24h, 7d, 30d
export function getHistoricalData(region: SingaporeRegion, timeframe: '24h' | '7d' | '30d'): HistoricalDataPoint[] {
  const base = REGIONAL_SUMMARIES[region];

  if (timeframe === '24h') {
    const hours = ['00:00', '02:00', '04:00', '06:00', '08:00', '10:00', '12:00', '14:00', '16:00', '18:00', '20:00', '22:00'];
    return hours.map((hour, idx) => {
      // Diurnal cycle
      const tempDelta = Math.sin((idx / 12) * Math.PI * 2 - Math.PI / 2) * 3.2;
      const humidityDelta = -tempDelta * 4;
      const pm25Variance = ((idx % 3) - 1) * 2;
      return {
        timestamp: `2026-10-24T${hour}:00Z`,
        timeLabel: hour,
        temperature: parseFloat((base.temperature + tempDelta).toFixed(1)),
        humidity: Math.min(95, Math.max(55, Math.round(base.humidity + humidityDelta))),
        psi: Math.max(25, Math.min(80, Math.round(base.psi + ((idx % 4) - 2) * 3))),
        pm25: Math.max(8, Math.min(45, Math.round(base.pm25 + pm25Variance))),
        rainfall: idx === 7 || idx === 8 ? parseFloat((1.8 * (idx === 7 ? 0.6 : 1.2)).toFixed(1)) : 0,
      };
    });
  }

  if (timeframe === '7d') {
    const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
    return days.map((day, idx) => ({
      timestamp: `2026-10-${18 + idx}`,
      timeLabel: day,
      temperature: parseFloat((base.temperature + (Math.sin(idx * 1.5) * 1.2)).toFixed(1)),
      humidity: Math.min(92, Math.max(65, Math.round(base.humidity + Math.cos(idx) * 6))),
      psi: Math.round(base.psi + (idx % 2 === 0 ? 3 : -2)),
      pm25: Math.round(base.pm25 + (idx % 3 === 0 ? 2 : -1)),
      rainfall: idx === 2 || idx === 5 ? (idx === 2 ? 12.4 : 6.8) : 0.4,
    }));
  }

  // 30d
  const points: HistoricalDataPoint[] = [];
  for (let i = 1; i <= 30; i++) {
    const dayStr = i < 10 ? `0${i}` : `${i}`;
    points.push({
      timestamp: `2026-10-${dayStr}`,
      timeLabel: `Oct ${i}`,
      temperature: parseFloat((base.temperature + Math.sin(i * 0.4) * 1.6).toFixed(1)),
      humidity: Math.min(94, Math.max(62, Math.round(base.humidity + Math.cos(i * 0.5) * 8))),
      psi: Math.round(base.psi + Math.sin(i) * 6),
      pm25: Math.max(9, Math.round(base.pm25 + Math.cos(i * 0.7) * 4)),
      rainfall: (i % 5 === 0) ? parseFloat((8.5 + (i % 3) * 4.2).toFixed(1)) : 0.2,
    });
  }
  return points;
}
